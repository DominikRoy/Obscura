"""Paired validation on public DroneFace inputs; every simulated role lives on this host."""

import argparse
import contextlib
import hashlib
import json
import os
from pathlib import Path

from A.oracle import decision, encode
from check import BANK, checked_pair, reference_probe
from run import BENCH, PROVISION, SETUP, Model, Session, cpu_worker
from setup_slot import exclusive, prepare


def main():
    from dataset_tee import prepare_face

    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--pairs",
        type=Path,
        required=True,
        help="pairs.json generated by A/pairs.py enroll",
    )
    p.add_argument("--ppface", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    bank = json.loads(BANK.read_text())
    key = os.urandom(32)
    with contextlib.closing(Session(True)) as ta:
        ta.call(PROVISION, key)
    model = Model(BENCH / "secure_sface/generated")
    records = []
    for pair in json.loads(args.pairs.read_text()):
        crop, _ = prepare_face(args.ppface / pair["probe"])
        pixels = crop.tobytes()
        x = encode(bank[pair["reference"]])
        profile = pair.get("threshold_profile", "lfw")
        row = dict(
            **pair,
            crop_sha256=hashlib.sha256(pixels).hexdigest(),
            plaintext=decision(x, reference_probe(model, pixels), profile),
        )
        for mode in "ABCQ":
            box, roles = prepare(mode, x, key, profile)
            with contextlib.closing(Session(True)) as ta:
                ta.call(SETUP, box)
                model.setup(ta, mode)
                output = model.extract(ta, mode, pixels, cpu_worker)
            row[mode] = checked_pair(roles, output) if roles else output[0]
        if row["A"] != row["B"] or row["A"] != row["plaintext"] or row["C"] != row["Q"]:
            raise RuntimeError("Protocol mismatch for " + pair["probe"])
        records.append(row)
    totals = {m: sum(r[m] == r["label"] for r in records) for m in "ABCQ"}
    result = {
        "backend": "native validation, simulated GPU",
        "pairs": len(records),
        "correct": totals,
        "quantization_decision_changes": sum(r["A"] != r["C"] for r in records),
    }
    exclusive(
        args.output, json.dumps(dict(**result, records=records), indent=2).encode()
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
