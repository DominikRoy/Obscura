"""Generate the TA's immutable Haar stumps from the notebook's OpenCV XML files."""

import argparse
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET


def model(directory, name, filename):
    raw = (directory / filename).read_bytes()
    root = ET.fromstring(raw).find("cascade")
    features = list(root.find("features"))
    lines = [
        f"/* {filename} SHA-256 {hashlib.sha256(raw).hexdigest()} */",
        f"static const struct stump {name}_trees[] = {{",
    ]
    stages = []
    for stage in root.findall("stages/_"):
        trees = stage.findall("weakClassifiers/_")
        stages.append((len(trees), float(stage.findtext("stageThreshold")) - 1e-5))
        for tree in trees:
            left, right, idx, threshold = tree.findtext("internalNodes").split()
            assert (left, right) == ("0", "-1")
            f = features[int(idx)]
            assert f.findtext("tilted", "0").strip() == "0"
            rects = [
                tuple(int(float(v)) for v in r.text.split())
                for r in f.findall("rects/_")
            ]
            assert 2 <= len(rects) <= 3
            values = [
                float(threshold),
                *map(float, tree.findtext("leafValues").split()),
            ]
            lines.append(
                "{"
                + ",".join(map(str, values))
                + ",{"
                + ",".join("{" + ",".join(map(str, r)) + "}" for r in rects)
                + "}},"
            )
    lines.extend(["};", f"static const struct stage {name}_stages[] = {{"])
    lines.extend("{%d,%s}," % entry for entry in stages)
    lines.extend(
        [
            "};",
            f"static const struct cascade {name} = "
            + "{%s,%d,%s_stages,%s_trees};"
            % (root.findtext("width"), len(stages), name, name),
        ]
    )
    notice = raw.decode().split("<!--", 1)[1].split("-->", 1)[0].strip()
    return "\n".join(lines), notice


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("opencv_data", type=Path)
    args = p.parse_args()
    dest = Path(__file__).parent
    models = [
        model(args.opencv_data, n, f)
        for n, f in [
            ("face", "haarcascade_frontalface_default.xml"),
            ("eye", "haarcascade_eye.xml"),
        ]
    ]
    (dest / "cascades.h").write_text(
        "/* Generated by export_cascades.py. See LICENSE.txt. */\n"
        + "\n".join(m[0] for m in models)
        + "\n"
    )
    (dest / "LICENSE.txt").write_text("\n\n".join(m[1] for m in models) + "\n")
